// --------- Database Class Definition ---------
/// The main database class for the application, built with Drift.
/// It lists all tables and DAOs that are part of this database.
@DriftDatabase(tables: [
  JuMappings,
  YuDingEntries,
  PresetPans,
  DbInitializationFlags,
], daos: [
  // LiuRenDao, // DAO for Liu Ren specific operations
])
class DaLiuRenAppDatabase extends _$DaLiuRenAppDatabase {
  DaLiuRenAppDatabase([QueryExecutor? e])
      : super(
          e ??
              driftDatabase(
                name: 'liuren_database',
                native: const DriftNativeOptions(
                  databaseDirectory: getApplicationSupportDirectory,
                ),
                web: DriftWebOptions(
                  sqlite3Wasm: Uri.parse('sqlite3.wasm'),
                  driftWorker: Uri.parse('drift_worker.js'),
                  onResult: (result) {
                    if (result.missingFeatures.isNotEmpty) {
                      print(
                        'Using ${result.chosenImplementation} due to unsupported '
                        'browser features: ${result.missingFeatures}',
                      );
                    }
                  },
                ),
              ),
        );

  /// Constructor for testing that uses an in-memory database
  DaLiuRenAppDatabase.forTesting(QueryExecutor executor) : super(executor);

  @override
  int get schemaVersion => 1;

  @override
  MigrationStrategy get migration {
    return MigrationStrategy(
      onCreate: (Migrator m) async {
        await m.createAll();
      },
      beforeOpen: (details) async {
        if (details.wasCreated) {
          // Create a bunch of default values so the app doesn't look too empty
          // on the first start.
        }

        await impl.validateDatabaseSchema(this);
      },
    );
  }

  Future<void> _executeSqlScript(String scriptPath) async {
    final sqlScript = await rootBundle.loadString(scriptPath);
    final statements = sqlScript
        .split(';')
        .map((s) => s.trim())
        .where((s) => s.isNotEmpty)
        .toList();

    for (final statement in statements) {
      await customStatement(statement);
    }
  }
}

/// Opens the database connection.
/// Uses [LazyDatabase] to open the connection on first use, potentially in a background isolate.
LazyDatabase _openConnection() {
  return LazyDatabase(() async {
    final dbFolder = await getApplicationDocumentsDirectory();
    final file = File(p.join(dbFolder.path, 'daliuren_db.sqlite'));
    return NativeDatabase.createInBackground(file);
  });
}

